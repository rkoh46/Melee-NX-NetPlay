#!/usr/bin/env python3
# Guest-register entry wrappers for the functions in a lowered module (docs/NATIVE_C.md):
#   tools/gml/gen_wrappers.py <gml_native.ll> <symbols.map> <out_dir>
# Writes gml_hle.cpp (HLE(name) { read r3../f1.. -> native call -> r3/f1 }) and gml_hooked.txt (the
# names the recompiler hooks). Only externally visible functions with a guest address are hooked.
# SPDX-License-Identifier: GPL-3.0-or-later
import re
import sys
from pathlib import Path

ll, symmap, out = Path(sys.argv[1]), Path(sys.argv[2]), Path(sys.argv[3])
syms, count = {}, {}
for line in symmap.read_text().splitlines():
    n, a = line.split()
    syms.setdefault(n, int(a, 16))
    count[n] = count.get(n, 0) + 1
# The recompiler hooks by name: a name several files use (their statics) would redirect all of them.
for n in [n for n, k in count.items() if k > 1]:
    syms.pop(n)
skip = set()
# Only functions the listed decomp files define are hooked (not header inlines such as memcpy).
sources = ""
files_list = Path(__file__).resolve().parents[2] / "port/recomp/gml_files.txt"
decomp = Path(__file__).resolve().parents[2] / "ref/melee"
for f in files_list.read_text().splitlines():
    f = f.strip()
    if f and not f.startswith("#"):
        sources += (decomp / f).read_text(errors="replace")
def defined_in_sources(name):
    return re.search(r"^[^\n;#]*\b%s\s*\([^;]*\)\s*\{" % re.escape(name), sources, re.M) is not None
CT = {"i8": "uint8_t", "i16": "uint16_t", "i32": "uint32_t", "i64": "uint64_t", "float": "float", "double": "double", "void": "void"}
protos, bodies, hooked = [], [], []
for m in re.finditer(r"^define (?!internal|private|linkonce|weak|available_externally)(.*?)@([\w.$]+)\((.*?)\)", ll.read_text(), re.M):
    pre, name, params = m.group(1), m.group(2), m.group(3)
    if not name.startswith("gml_"):
        continue
    native, name = name, name[4:]
    if name.startswith("gml_") or name not in syms or name in skip or not defined_in_sources(name):
        continue
    rt = re.findall(r"\b(void|i8|i16|i32|i64|float|double)\b", pre)[-1]
    rext = "s" if "signext" in pre else "z"
    ptypes = [re.search(r"\b(i8|i16|i32|i64|float|double)\b", p).group(1) for p in params.split(",") if p.strip()]
    gi, fi, args = 3, 1, []
    ok = True
    for t in ptypes:
        if t in ("float", "double"):
            args.append("(%s)c.f[%d].ps0" % (CT[t], fi)); fi += 1
        elif t == "i64":
            gi += (gi % 2 == 0)
            args.append("((uint64_t)c.r[%d] << 32 | c.r[%d])" % (gi, gi + 1)); gi += 2
        elif gi > 10:   # EABI: the caller's parameter area at 8(r1)
            args.append("(%s)ppc::ld32(c, m, c.r[1] + %du)" % (CT[t], 8 + 4 * (gi - 11))); gi += 1
        else:
            args.append("(%s)c.r[%d]" % (CT[t], gi)); gi += 1
    if fi > 9:
        continue
    protos.append("%s %s(%s);" % (CT[rt], native, ", ".join(CT[t] for t in ptypes) or "void"))
    call = "%s(%s)" % (native, ", ".join(args))
    if rt == "void":
        body = call + ";"
    elif rt in ("float", "double"):
        body = "c.f[1].ps0 = c.f[1].ps1 = (double)%s;" % call
    elif rt == "i64":
        body = "{ const uint64_t v = %s; c.r[3] = uint32_t(v >> 32); c.r[4] = uint32_t(v); }" % call
    else:
        body = "c.r[3] = uint32_t(%s(%s));" % ("int32_t" if rext == "s" else "uint32_t", ("(int%s_t)" % rt[1:] if rext == "s" else "") + call)
    bodies.append("HLE(%s) { gml_enter(c, m); GML_VERIFIED(%s, guest::f_%08X_orig, [&] { %s }); }" % (name, name, syms[name], body))
    protos.append("namespace guest { void f_%08X_orig(ppc::Context&, uint8_t*); }" % syms[name])
    hooked.append(name)
cpp = ["// Generated by tools/gml/gen_wrappers.py from the lowered module.", '#include "hle.h"', '#include "gml_glue.h"',
       "#include <cstdint>", 'extern "C" {'] + [p for p in protos if not p.startswith("namespace")] + ["}"]
cpp += [p for p in protos if p.startswith("namespace")] + bodies
(out / "gml_hle.cpp").write_text("\n".join(cpp) + "\n")
(out / "gml_hooked.txt").write_text("\n".join(hooked) + "\n")
print("gml: %d functions hooked" % len(hooked))
