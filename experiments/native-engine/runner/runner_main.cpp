struct Options {
#ifdef __SWITCH__
  std::string iso = "sdmc:/switch/melee-nx-netplay/GALE01.iso";
  std::string out_dir = "sdmc:/switch/mu-native";
#else
  std::string iso;
  std::string out_dir = "./mu-native-out";
#endif
  std::string script = "parity_vs_onett";
  std::string game;                 // empty: the embedded image
  uint32_t frames = 9000;
  uint32_t snapshot_at = 0;         // VS match frame at which the snapshot is timed; 0 = off
  bool print_digest = false;
};

FILE* run_log = nullptr;
void say(const char* format, ...) {
  char line[2048];
  va_list args; va_start(args, format); std::vsnprintf(line, sizeof line, format, args); va_end(args);
  std::printf("%s\n", line); std::fflush(stdout);
  if (run_log) { std::fprintf(run_log, "%s\n", line); std::fflush(run_log); }
#ifdef __SWITCH__
  consoleUpdate(nullptr);
#endif
}

uint64_t fnv1a64(const std::string& bytes) {
  uint64_t h = 0xcbf29ce484222325ull;
  for (unsigned char c : bytes) { h ^= c; h *= 0x100000001b3ull; }
  return h;
}

// The reference digest: text of the CSV and where each row starts.
struct Reference {
  std::string text;
  std::vector<uint32_t> row;        // offset of row i; row.size() == rows + 1
  bool loaded() const { return row.size() > 1; }
  size_t rows() const { return row.empty() ? 0 : row.size() - 1; }
  std::string at(size_t i) const { return text.substr(row[i], row[i + 1] - row[i] - 1); }   // without the newline
};
bool load_reference(const std::string& script, Reference* out) {
  for (size_t i = 0; i < mu_embedded_reference_count; ++i) {
    const auto& file = mu_embedded_references[i];
    if (script != file.name) continue;
    z_stream z{};
    if (inflateInit2(&z, 16 + MAX_WBITS) != Z_OK) return false;
    z.next_in = const_cast<Bytef*>(file.begin); z.avail_in = uInt(file.end - file.begin);
    char block[65536]; int rc = Z_OK;
    while (rc == Z_OK) {
      z.next_out = reinterpret_cast<Bytef*>(block); z.avail_out = sizeof block;
      rc = inflate(&z, Z_NO_FLUSH);
      out->text.append(block, sizeof block - z.avail_out);
    }
    inflateEnd(&z);
    if (rc != Z_STREAM_END) { out->text.clear(); return false; }
    out->row.push_back(0);
    for (size_t at = 0; at < out->text.size(); ++at) if (out->text[at] == '\n') out->row.push_back(uint32_t(at + 1));
    return true;
  }
  return false;
}

const char* column_name(size_t column) {
  static const char* head[] = {"retrace", "scene_major", "scene", "match_frame", "rng"};
  static const char* fighter[] = {"present", "stocks", "action", "anim_frame", "pos_x", "pos_y", "pos_z", "vel_x", "vel_y", "vel_z", "percent", "facing"};
  static char name[32];
  if (column < 5) return head[column];
  std::snprintf(name, sizeof name, "p%zu.%s", (column - 5) / 12 + 1, fighter[(column - 5) % 12]);
  return name;
}
// First column in which two CSV rows differ, with both values.
std::string first_difference(const std::string& ours, const std::string& theirs) {
  size_t a = 0, b = 0, column = 0;
  for (;; ++column) {
    const size_t ea = std::min(ours.find(',', a), ours.size()), eb = std::min(theirs.find(',', b), theirs.size());
    const std::string va = ours.substr(a, ea - a), vb = theirs.substr(b, eb - b);
    if (va != vb) return std::string(column_name(column)) + ": this run " + va + ", reference " + vb;
    if (ea >= ours.size() || eb >= theirs.size()) return "row lengths differ";
    a = ea + 1; b = eb + 1;
  }
}
// "1-131:24/0 132-401:0/0 ..." from the scene columns of a digest.
struct Scene { uint32_t first, major, minor; };
std::string timeline(const std::vector<Scene>& scenes, uint32_t last) {
  std::string text;
  for (size_t i = 0; i < scenes.size(); ++i) {
    char part[64];
    std::snprintf(part, sizeof part, "%s%u-%u:%u/%u", i ? " " : "", scenes[i].first, i + 1 < scenes.size() ? scenes[i + 1].first - 1 : last,
                  scenes[i].major, scenes[i].minor);
    text += part;
  }
  return text;
}
void note_scene(std::vector<Scene>* scenes, uint32_t retrace, uint32_t major, uint32_t minor) {
  if (scenes->empty() || scenes->back().major != major || scenes->back().minor != minor) scenes->push_back({retrace, major, minor});
}

struct Frame { float ms; bool vs_match; bool fighting; bool disc; bool excluded; };
struct Run {
  Options options;
  Reference reference;
  std::string digest;                 // the CSV, kept in memory so storage never sits inside a timed frame
  std::vector<Frame> frames;
  std::vector<Scene> scenes;
  Clock::time_point last;
  bool have_last = false;
  uint32_t last_match_frame = 0;
  uint64_t last_disc_reads = 0;
  bool snapshot_done = false;
  uint32_t match_first = 0, match_last = 0;
  // Comparison with the reference.
  uint32_t first_diff = 0, diff_in_match = 0, diff_outside = 0, compared = 0;
  std::string diff_ours, diff_reference;
} run_state;

double ms_since(Clock::time_point start) { return std::chrono::duration<double, std::milli>(Clock::now() - start).count(); }

// One full snapshot of what a rollback saves, and its restore, as the engine does it where the
// operating system offers no write tracking: every byte of the ranges is copied.
void time_snapshot(uint32_t match_frame) {
  const auto& game = linux_host::game_api();
  std::vector<MuStateRegion> ranges(game.snapshot_ranges(nullptr, 0));
  ranges.resize(game.snapshot_ranges(ranges.data(), uint32_t(ranges.size())));
  std::vector<MuStateRegion> exclusions(game.state_exclusions(nullptr, 0));
  exclusions.resize(game.state_exclusions(exclusions.data(), uint32_t(exclusions.size())));
  const auto spans = native_savestate::subtract(ranges, exclusions);
  size_t bytes = 0;
  for (const auto& span : spans) bytes += span.size;
  const uint64_t before = native_savestate::hash_spans(spans);
  native_savestate::Snapshot snapshot;
  double save[5], restore[5];
  for (int i = 0; i < 5; ++i) {
    auto t = Clock::now(); snapshot.capture(spans); save[i] = ms_since(t);
    t = Clock::now(); snapshot.restore(); restore[i] = ms_since(t);
  }
  const bool unchanged = native_savestate::hash_spans(spans) == before;
  say("snapshot at VS match frame %u: %zu ranges (%zu after exclusions), %.1f MiB", match_frame, ranges.size(), spans.size(), bytes / 1048576.0);
  say("snapshot save ms:    %.2f %.2f %.2f %.2f %.2f (first includes allocating the buffer)", save[0], save[1], save[2], save[3], save[4]);
  say("snapshot restore ms: %.2f %.2f %.2f %.2f %.2f", restore[0], restore[1], restore[2], restore[3], restore[4]);
  say("snapshot: state %s by save and restore", unchanged ? "unchanged" : "CHANGED (this run's digest is not valid)");
}

// Called by the host once per retrace, after the game has simulated the frame.
void observe(const MuStatePod& state, const linux_host::Counters& counters, void*) {
  auto& r = run_state;
  const auto now = Clock::now();
  const bool fighting = state.match_frame && state.match_frame != r.last_match_frame;   // fighters simulated this retrace
  const bool vs_match = fighting && state.scene_major == 2 && state.scene == 2;
  bool excluded = false;

  char row[1400]; int n = 0;
  n += std::snprintf(row + n, sizeof row - n, "%u,%u,%u,%u,%u", counters.retraces, state.scene_major, state.scene, state.match_frame, state.rng);
  for (const auto& f : state.player)
    n += std::snprintf(row + n, sizeof row - n, ",%u,%u,%u,%u,%u,%u,%u,%u,%u,%u,%u,%u", f.present, f.stocks, f.action, f.anim_frame,
                       f.pos_x, f.pos_y, f.pos_z, f.vel_x, f.vel_y, f.vel_z, f.percent, f.facing);
  row[n++] = '\n';
  r.digest.append(row, size_t(n));
  if (r.options.print_digest) { std::fwrite(row, 1, size_t(n), stdout); }
  note_scene(&r.scenes, counters.retraces, state.scene_major, state.scene);

  const size_t index = counters.retraces - 1;
  if (r.reference.loaded() && index < r.reference.rows()) {
    ++r.compared;
    const uint32_t begin = r.reference.row[index], length = r.reference.row[index + 1] - begin;
    if (length != uint32_t(n) || std::memcmp(r.reference.text.data() + begin, row, size_t(n)) != 0) {
      if (vs_match) ++r.diff_in_match; else ++r.diff_outside;
      if (!r.first_diff) {
        r.first_diff = counters.retraces;
        r.diff_ours.assign(row, size_t(n - 1));
        r.diff_reference = r.reference.at(index);
        say("DIVERGED from the reference at retrace %u (%s)", counters.retraces, first_difference(r.diff_ours, r.diff_reference).c_str());
      }
    }
  }

  if (vs_match) {
    if (!r.match_first) r.match_first = counters.retraces;
    r.match_last = counters.retraces;
    if (!r.snapshot_done && r.options.snapshot_at && state.match_frame >= r.options.snapshot_at) {
      r.snapshot_done = true; excluded = true;
      time_snapshot(state.match_frame);
    }
  }
  if (r.have_last)
    r.frames.push_back({float(std::chrono::duration<double, std::milli>(now - r.last).count()), vs_match, fighting,
                        counters.disc_reads != r.last_disc_reads, false});
  if (counters.retraces % 600 == 0)
    say("retrace %u: scene %u/%u, match frame %u", counters.retraces, state.scene_major, state.scene, state.match_frame);
  r.last_match_frame = state.match_frame;
  r.last_disc_reads = counters.disc_reads;
  r.last = Clock::now();   // the digest text, the comparison, the snapshot timing and the progress line are not part of the next frame
  r.have_last = true;
  (void)excluded;
}

enum class Which { VsMatch, Fighting, All };
void report_timing(const char* label, Which which, bool with_disc_frames) {
  std::vector<float> ms;
  for (const auto& f : run_state.frames) {
    const bool wanted = which == Which::All || (which == Which::VsMatch ? f.vs_match : f.fighting);
    if (wanted && (with_disc_frames || !f.disc)) ms.push_back(f.ms);
  }
  if (ms.empty()) { say("%s: none", label); return; }
  double sum = 0; for (float v : ms) sum += v;
  std::vector<float> sorted = ms; std::sort(sorted.begin(), sorted.end());
  size_t late = 0; for (float v : ms) if (v > 1000.0f / 60) ++late;
  say("%s: %zu frames, avg %.3f ms, median %.3f, p99 %.3f, worst %.3f, over 16.67 ms: %zu", label, ms.size(), sum / ms.size(),
      sorted[sorted.size() / 2], sorted[size_t(sorted.size() * 0.99)], sorted.back(), late);
}

bool write_file(const std::string& path, const void* data, size_t size) {
  FILE* out = std::fopen(path.c_str(), "wb");
  if (!out) return false;
  const bool ok = std::fwrite(data, 1, size, out) == size;
  return std::fclose(out) == 0 && ok;
}

// A match must start from an empty memory card every time, as the reference runs did.
void empty_directory(const std::string& path) {
  mkdir(path.c_str(), 0777);
  DIR* dir = opendir(path.c_str());
  if (!dir) return;
  std::vector<std::string> names;
  while (dirent* entry = readdir(dir)) if (entry->d_name[0] != '.') names.push_back(entry->d_name);
  closedir(dir);
  for (const auto& name : names) std::remove((path + "/" + name).c_str());
}

// A script name is looked up among the embedded scripts (which are written to <out>/scripts,
// because the host's script reader takes a path), then as <out>/scripts/<name>.txt. A path is used as it is.
std::string script_path(const Options& options) {
  if (options.script.find('/') != std::string::npos || options.script.find(".txt") != std::string::npos) return options.script;
  const std::string dir = options.out_dir + "/scripts", path = dir + "/" + options.script + ".txt";
  for (size_t i = 0; i < mu_embedded_script_count; ++i) {
    const auto& s = mu_embedded_scripts[i];
    if (options.script != s.name) continue;
    mkdir(dir.c_str(), 0777);
    if (!write_file(path, s.begin, size_t(s.end - s.begin))) say("cannot write %s", path.c_str());
    return path;
  }
  return path;
}

void report_thread() {
  // The simulation relies on default floating-point behaviour: round to nearest, no flush-to-zero.
  unsigned long fpcr; __asm__ volatile("mrs %0, fpcr" : "=r"(fpcr));
  say("simulation thread: FPCR %lx%s", fpcr, fpcr ? " (EXPECTED 0)" : " (round to nearest, as expected)");
  int marker = 0;
#ifdef __SWITCH__
  MemoryInfo mi; u32 page_info;
  if (R_SUCCEEDED(svcQueryMemory(&mi, &page_info, (u64)(uintptr_t)&marker)))
    say("simulation thread: stack mapping %lx..%lx = %lu KiB (asked for 8192), %lu KiB below the current frame", (unsigned long)mi.addr,
        (unsigned long)(mi.addr + mi.size), (unsigned long)(mi.size >> 10), (unsigned long)(((uintptr_t)&marker - mi.addr) >> 10));
#else
  pthread_attr_t attr; void* base = nullptr; size_t size = 0;
  if (pthread_getattr_np(pthread_self(), &attr) == 0) {
    pthread_attr_getstack(&attr, &base, &size); pthread_attr_destroy(&attr);
    say("simulation thread: stack %zu KiB (asked for 8192), %zu KiB below the current frame", size >> 10, ((uintptr_t)&marker - (uintptr_t)base) >> 10);
  }
#endif
}

int simulate(const Options& options) {
  auto& r = run_state;
  r.options = options;
  r.digest.reserve(size_t(options.frames) * 330);
  r.frames.reserve(options.frames);
  report_thread();
  if (load_reference(options.script, &r.reference)) say("reference digest for %s: %zu rows (x86-64 AVX2+FMA build)", options.script.c_str(), r.reference.rows());
  else say("no embedded reference digest for %s: exactness cannot be judged by this run", options.script.c_str());

  linux_host::Config config;
  config.iso_path = options.iso;
  config.game_path = options.game.empty() ? "(embedded)" : options.game;
  config.log_path = options.out_dir + "/host.log";
  config.card_dir = options.out_dir + "/card";
  config.input_script = script_path(options);
  config.max_frames = options.frames;
  config.pace = false; config.headless = true; config.no_gc_adapter = true; config.vanilla_game = true;
  config.has_rng_seed = true; config.rng_seed = 0x12345678;
  config.has_time_base = true; config.time_base = 0;
  empty_directory(config.card_dir);
  if (options.game.empty()) mac_elf::set_embedded_image(mu_embedded_game, size_t(mu_embedded_game_end - mu_embedded_game));

  say("disc %s | script %s | %u retraces | image %s | snapshot timing %s", options.iso.c_str(), options.script.c_str(), options.frames,
      config.game_path.c_str(), options.snapshot_at ? "on" : "off");
  std::string error;
  const auto t0 = Clock::now();
  if (!linux_host::initialize(config, &error)) { say("cannot start: %s", error.c_str()); linux_host::shutdown(); return 1; }
  say("started in %.0f ms; image at 0x82800000 (%u bytes)", ms_since(t0), linux_host::game_image_size());
  linux_host::set_frame_observer(observe, nullptr);
  const auto t1 = Clock::now();
  const int result = linux_host::run();
  const double total = ms_since(t1);
  const auto stats = linux_host::counters();
  say("stopped with code %d after %u retraces in %.1f s: %llu disc reads, %llu FIFO bytes, %llu audio blocks", result, stats.retraces,
      total / 1000, (unsigned long long)stats.disc_reads, (unsigned long long)stats.fifo_bytes, (unsigned long long)stats.audio_blocks);
  linux_host::set_frame_observer(nullptr, nullptr);
  linux_host::shutdown();      // unloads the image and unmaps the three fixed ranges

  // Where the run went: retrace ranges per scene (major/minor). 2/2 is the VS match.
  say("scenes, this run:  %s", timeline(r.scenes, stats.retraces).c_str());
  if (r.reference.loaded()) {
    std::vector<Scene> expected;
    for (size_t i = 0; i < r.reference.rows() && i < stats.retraces; ++i) {
      unsigned retrace = 0, major = 0, minor = 0;
      std::sscanf(r.reference.text.c_str() + r.reference.row[i], "%u,%u,%u", &retrace, &major, &minor);
      note_scene(&expected, retrace, major, minor);
    }
    const std::string theirs = timeline(expected, uint32_t(std::min<size_t>(r.reference.rows(), stats.retraces)));
    if (theirs != timeline(r.scenes, stats.retraces)) say("scenes, reference: %s", theirs.c_str());
    else say("scenes: same sequence and timing as the reference");
  }

  if (r.match_first) say("VS match: retraces %u..%u", r.match_first, r.match_last);
  else say("VS match: NOT REACHED (the menu flow did not get to scene 2/2; see the scene lines and the host log for card errors)");
  report_timing("VS match frames, all", Which::VsMatch, true);
  report_timing("VS match frames without a disc read", Which::VsMatch, false);
  report_timing("any frames with fighters simulating (includes demo fights)", Which::Fighting, true);
  report_timing("all retraces (menus, loading, matches)", Which::All, true);
  say("each frame is the whole retrace on one core: simulation, the GX command stream (discarded), audio mixing (discarded)");
  if (options.snapshot_at && !r.snapshot_done) say("snapshot: NOT TIMED, the VS match never reached frame %u", options.snapshot_at);

  const uint64_t hash = fnv1a64(r.digest);
  const std::string csv = options.out_dir + "/digest-" + (options.script.find('/') == std::string::npos ? options.script : std::string("custom")) + ".csv";
  say("digest: %u rows, fnv1a64 %016llx, %s %s", stats.retraces, (unsigned long long)hash,
      write_file(csv, r.digest.data(), r.digest.size()) ? "written to" : "COULD NOT WRITE", csv.c_str());
  if (r.reference.loaded()) {
    if (!r.first_diff)
      say("digest vs x86-64 AVX2 reference: IDENTICAL for all %u rows compared%s", r.compared,
          r.compared < stats.retraces ? " (the reference is shorter than this run)" : "");
    else {
      say("digest vs x86-64 AVX2 reference: DIFFERENT. First differing retrace %u: %s", r.first_diff,
          first_difference(r.diff_ours, r.diff_reference).c_str());
      say("  this run : %s", r.diff_ours.c_str());
      say("  reference: %s", r.diff_reference.c_str());
      say("  differing rows: %u inside the VS match, %u outside, of %u compared", r.diff_in_match, r.diff_outside, r.compared);
    }
  }
  return result;
}

struct ThreadArgs { Options options; int result; };
void* simulate_thread(void* user) {
  auto* args = static_cast<ThreadArgs*>(user);
  args->result = simulate(args->options);
  return nullptr;
}

void usage() {
  say("mu-native [--iso PATH] [--script NAME|PATH] [--frames N] [--out DIR] [--game melee_game.so]");
  say("          [--snapshot-at VS_MATCH_FRAME] [--print-digest]");
  std::string names;
  for (size_t i = 0; i < mu_embedded_script_count; ++i) names += std::string(" ") + mu_embedded_scripts[i].name;
  say("embedded scripts:%s", names.c_str());
}
