// Measurement only (--dirty-dump FILE): exact per-frame dirty pages, found by comparing every page
// of the snapshot ranges with a copy from the previous frame. Record: u32 match_frame, u32 count,
// count * u32 page address. A header record (match_frame 0xFFFFFFFF) lists the spans as address,size pairs.
struct DirtyDump {
  FILE* out = nullptr;
  std::vector<native_savestate::Span> spans;
  std::vector<std::vector<uint8_t>> shadow;
  std::vector<uint32_t> pages;
} dirty;
std::vector<native_savestate::Span> snapshot_spans() {
  const auto& game = linux_host::game_api();
  std::vector<MuStateRegion> ranges(game.snapshot_ranges(nullptr, 0));
  ranges.resize(game.snapshot_ranges(ranges.data(), uint32_t(ranges.size())));
  std::vector<MuStateRegion> exclusions(game.state_exclusions(nullptr, 0));
  exclusions.resize(game.state_exclusions(exclusions.data(), uint32_t(exclusions.size())));
  return native_savestate::subtract(ranges, exclusions);
}
void dirty_frame(uint32_t match_frame) {
  auto& d = dirty;
  if (d.spans.empty()) {
    d.spans = snapshot_spans();
    std::vector<uint32_t> header{0xFFFFFFFFu, uint32_t(d.spans.size() * 2)};
    for (const auto& span : d.spans) {
      d.shadow.emplace_back(span.address, span.address + span.size);
      header.push_back(uint32_t(uintptr_t(span.address))); header.push_back(span.size);
    }
    std::fwrite(header.data(), 4, header.size(), d.out);
    const auto& game = linux_host::game_api();
    std::vector<MuStateRegion> ranges(game.snapshot_ranges(nullptr, 0));
    ranges.resize(game.snapshot_ranges(ranges.data(), uint32_t(ranges.size())));
    for (const auto& range : ranges) std::printf("dirty-dump: snapshot range %08lx +%u\n", (unsigned long)uintptr_t(range.address), range.size);
    return;
  }
  d.pages.clear();
  for (size_t i = 0; i < d.spans.size(); ++i) {
    const uintptr_t begin = uintptr_t(d.spans[i].address), end = begin + d.spans[i].size;
    for (uintptr_t at = begin; at < end;) {
      const uintptr_t next = std::min(end, (at + 4096) & ~uintptr_t(4095));
      uint8_t* copy = d.shadow[i].data() + (at - begin);
      if (std::memcmp(copy, reinterpret_cast<void*>(at), next - at)) {
        std::memcpy(copy, reinterpret_cast<void*>(at), next - at);
        d.pages.push_back(uint32_t(at & ~uintptr_t(4095)));
      }
      at = next;
    }
  }
  const uint32_t head[2] = {match_frame, uint32_t(d.pages.size())};
  std::fwrite(head, 4, 2, d.out);
  std::fwrite(d.pages.data(), 4, d.pages.size(), d.out);
}

double ms_since(Clock::time_point start) { return std::chrono::duration<double, std::milli>(Clock::now() - start).count(); }

// One full snapshot of what a rollback saves, and its restore, as the engine does it where the
// operating system offers no write tracking: every byte of the ranges is copied.
void time_snapshot(uint32_t match_frame) {
  const auto& game = linux_host::game_api();
  std::vector<MuStateRegion> ranges(game.snapshot_ranges(nullptr, 0));
  ranges.resize(game.snapshot_ranges(ranges.data(), uint32_t(ranges.size())));
  std::vector<MuStateRegion> exclusions(game.state_exclusions(nullptr, 0));
  exclusions.resize(game.state_exclusions(exclusions.data(), uint32_t(exclusions.size())));
  const auto spans = native_savestate::subtract(ranges, exclusions);
  size_t bytes = 0;
  for (const auto& span : spans) bytes += span.size;
  const uint64_t before = native_savestate::hash_spans(spans);
  native_savestate::Snapshot snapshot;
  double save[5], restore[5];
  for (int i = 0; i < 5; ++i) {
    auto t = Clock::now(); snapshot.capture(spans); save[i] = ms_since(t);
    t = Clock::now(); snapshot.restore(); restore[i] = ms_since(t);
  }
  const bool unchanged = native_savestate::hash_spans(spans) == before;
  say("snapshot at VS match frame %u: %zu ranges (%zu after exclusions), %.1f MiB", match_frame, ranges.size(), spans.size(), bytes / 1048576.0);
  say("snapshot save ms:    %.2f %.2f %.2f %.2f %.2f (first includes allocating the buffer)", save[0], save[1], save[2], save[3], save[4]);
  say("snapshot restore ms: %.2f %.2f %.2f %.2f %.2f", restore[0], restore[1], restore[2], restore[3], restore[4]);
  say("snapshot: state %s by save and restore", unchanged ? "unchanged" : "CHANGED (this run's digest is not valid)");
}

// Rollback test: save every VS match frame; every `rollback_every` frames restore the state of
// `rollback_depth` frames earlier and let the game simulate those frames again (the scripted inputs
// depend only on the match frame, so they repeat). Every row, first pass or repeated, is compared
// with the reference row of the same match frame. Returns the match frame the game is at afterwards.
uint32_t rollback_step(uint32_t frame, double frame_ms, const char* row, int length, bool disc_quiet) {
  auto& r = run_state;
  const auto& o = r.options;
  if (!mu_rollback::active()) {
    if (r.rb_failed) return frame;
    std::string error;
    if (!mu_rollback::begin(snapshot_spans(), int(o.rollback_depth) + 2, o.rollback_verify, &error)) {
      r.rb_failed = true; say("rollback: cannot start tracking: %s", error.c_str()); return frame;
    }
    r.rb_next = frame + 120;
    r.rb_last_faults = dirtytrack_faults();
    say("rollback: tracking %zu pages (%.1f MiB) from VS match frame %u; every %u frames go back %u", mu_rollback::tracked_pages(),
        mu_rollback::tracked_pages() / 256.0, frame, o.rollback_every, o.rollback_depth);
  }
  // Exactness: this frame's state against the reference state of the same match frame.
  const char* comma = static_cast<const char*>(std::memchr(row, ',', size_t(length)));
  const auto expected = r.reference_by_frame.find(frame);
  if (comma && expected != r.reference_by_frame.end()) {
    ++r.rb_compared;
    const size_t mine = size_t(row + length - 1 - (comma + 1));      // without the newline
    if (mine != expected->second.second || std::memcmp(comma + 1, r.reference.text.data() + expected->second.first, mine)) {
      if (std::getenv("MU_ROLLBACK_DIFFS") && r.rb_different < 40)
        say("rollback diff: match frame %u pending %u rollback %u: %s", frame, r.rb_pending, r.rb_count,
            first_difference("0," + std::string(comma + 1, mine), "0," + r.reference.text.substr(expected->second.first, expected->second.second)).c_str());
      if (!r.rb_different++) {
        r.rb_first_different = frame;
        say("rollback: DIVERGED at VS match frame %u (%s), %u rollbacks so far, %s", frame,
            first_difference("0," + std::string(comma + 1, mine), "0," + r.reference.text.substr(expected->second.first, expected->second.second)).c_str(),
            r.rb_count, r.rb_pending ? "in a repeated frame" : "not in a repeated frame");
      }
    }
  }
  // One retrace should be one match frame. More means the game ran two frames on one pad sample
  // (its pad alarm fired twice), which shifts the scripted inputs: a property of this test, not of rollback.
  if (r.rb_expected_frame && frame != r.rb_expected_frame) { if (!r.rb_frame_jumps++) r.rb_first_jump = frame; }
  r.rb_expected_frame = frame + 1;
  const uint64_t faults = dirtytrack_faults();
  r.faults_per_frame.push_back(uint32_t(faults - r.rb_last_faults));
  r.rb_last_faults = faults;

  auto t = Clock::now();
  mu_rollback::save(int32_t(frame));
  const double save = ms_since(t);
  r.save_ms.push_back(float(save));
  // Diagnosis (--rollback-diff): once the repeated frames are back at the frame the rollback started
  // from, the state should be what it was then. List where it is not.
  if (o.rollback_diff && r.rb_pending == 2 && frame == r.rb_remembered_frame) {
    const auto diffs = mu_rollback::differences_from_remembered(64);
    if (!diffs.empty() && r.rb_diff_reports < 6) {
      ++r.rb_diff_reports;
      std::string text;
      char part[48];
      for (size_t i = 0; i < diffs.size() && i < 24; ++i) { std::snprintf(part, sizeof part, " %lx+%u", (unsigned long)diffs[i].first, diffs[i].second); text += part; }
      say("rollback diff: after repeating up to match frame %u, %zu%s byte runs differ from the first pass:%s", frame, diffs.size(), diffs.size() >= 64 ? "+" : "", text.c_str());
    }
    if (!diffs.empty()) ++r.rb_diff_rollbacks;
  }
  if (r.rb_pending) {
    (r.rb_pending > 1 ? r.repeated_ms : r.new_ms).push_back(float(frame_ms));
    r.rb_total += frame_ms + save;
    if (--r.rb_pending == 0) r.rollback_ms.push_back(float(r.rb_total));
    return frame;
  }
  // Not across a disc read: this host lets the game stream its music from the disc, the stream's
  // position is audio state (outside the snapshot, as designed) but its pending read requests are
  // not, so restoring over one leaves the two out of step. melee-unlocked's full host plays the
  // music itself and has no such reads during a match.
  r.first_pass_ms.push_back(float(frame_ms));
  if (frame < r.rb_next || frame <= o.rollback_depth || !disc_quiet || !mu_rollback::has(int32_t(frame - o.rollback_depth))) return frame;
  if (o.rollback_verify) { r.rb_missed += mu_rollback::missed_writes(); ++r.rb_checks; }
  if (o.rollback_diff) { mu_rollback::remember(); r.rb_remembered_frame = frame; }
  t = Clock::now();
  mu_rollback::restore(int32_t(frame - o.rollback_depth));
  const double restore = ms_since(t);
  if (!o.rollback_keep_clock) linux_host::rewind_frames(o.rollback_depth);
  if (!o.rollback_draw) linux_host::skip_draws(o.rollback_depth);   // the repeated frames are simulated, not drawn
  r.restore_ms.push_back(float(restore));
  r.rb_total = restore;
  r.rb_pending = o.rollback_depth + 1;     // the repeated frames and the next new one make up one real rollback frame
  r.rb_next = frame + o.rollback_every;
  ++r.rb_count;
  r.rb_expected_frame = frame - o.rollback_depth + 1;
  return frame - o.rollback_depth;
}

void report_series(const char* label, std::vector<float> values) {
  if (values.empty()) { say("%s: none", label); return; }
  double sum = 0; for (float v : values) sum += v;
  std::sort(values.begin(), values.end());
  say("%s: %zu, avg %.3f ms, median %.3f, p99 %.3f, worst %.3f", label, values.size(), sum / values.size(), values[values.size() / 2],
      values[size_t(values.size() * 0.99)], values.back());
}

// Called by the host once per retrace, after the game has simulated the frame.
void observe(const MuStatePod& state, const linux_host::Counters& counters, void*) {
  auto& r = run_state;
  const auto now = Clock::now();
  const bool fighting = state.match_frame && state.match_frame != r.last_match_frame;   // fighters simulated this retrace
  const bool vs_match = fighting && state.scene_major == 2 && state.scene == 2;
  bool excluded = false;

  char row[1400]; int n = 0;
  n += std::snprintf(row + n, sizeof row - n, "%u,%u,%u,%u,%u", counters.retraces, state.scene_major, state.scene, state.match_frame, state.rng);
  for (const auto& f : state.player)
    n += std::snprintf(row + n, sizeof row - n, ",%u,%u,%u,%u,%u,%u,%u,%u,%u,%u,%u,%u", f.present, f.stocks, f.action, f.anim_frame,
                       f.pos_x, f.pos_y, f.pos_z, f.vel_x, f.vel_y, f.vel_z, f.percent, f.facing);
  row[n++] = '\n';
  r.digest.append(row, size_t(n));
  if (r.options.print_digest) { std::fwrite(row, 1, size_t(n), stdout); }
  note_scene(&r.scenes, counters.retraces, state.scene_major, state.scene);

  const double frame_ms = r.have_last ? std::chrono::duration<double, std::milli>(now - r.last).count() : 0;
  const uint64_t observer_in = r.options.profile ? hostprof::now() : 0;
  if (r.options.profile) {
    hostprof::Sample sample; hostprof::read(&sample);
    const int kind = !vs_match ? 2 : (r.options.rollback_every && r.rb_pending > 1) ? 1 : 0;
    if (r.have_last) {
      for (int i = 0; i < hostprof::kSlots; ++i) {
        r.prof_calls[kind][i] += sample.calls[i] - r.prof_last.calls[i];
        r.prof_ticks[kind][i] += sample.ticks[i] - r.prof_last.ticks[i];
      }
      r.prof_frame_ms[kind] += frame_ms; ++r.prof_frames[kind];
    }
    r.prof_last = sample;
  }
  uint32_t game_frame = state.match_frame;        // differs from state.match_frame right after a rollback
  if (r.options.rollback_every) {
    if (counters.disc_reads != r.last_disc_reads) r.rb_last_disc_retrace = counters.retraces;
    if (vs_match) game_frame = rollback_step(state.match_frame, frame_ms, row, n, counters.retraces - r.rb_last_disc_retrace > r.options.rollback_depth + 2);
    else if (mu_rollback::active() && !(state.scene_major == 2 && state.scene == 2)) mu_rollback::end();   // the match is over
  }
  const size_t index = counters.retraces - 1;
  if (!r.options.rollback_every && r.reference.loaded() && index < r.reference.rows()) {
    ++r.compared;
    const uint32_t begin = r.reference.row[index], length = r.reference.row[index + 1] - begin;
    if (length != uint32_t(n) || std::memcmp(r.reference.text.data() + begin, row, size_t(n)) != 0) {
      if (vs_match) ++r.diff_in_match; else ++r.diff_outside;
      if (!r.first_diff) {
        r.first_diff = counters.retraces;
        r.diff_ours.assign(row, size_t(n - 1));
        r.diff_reference = r.reference.at(index);
        say("DIVERGED from the reference at retrace %u (%s)", counters.retraces, first_difference(r.diff_ours, r.diff_reference).c_str());
      }
    }
  }

  if (vs_match && dirty.out) dirty_frame(state.match_frame);
  if (vs_match) {
    if (!r.match_first) r.match_first = counters.retraces;
    r.match_last = counters.retraces;
    if (!r.snapshot_done && r.options.snapshot_at && state.match_frame >= r.options.snapshot_at) {
      r.snapshot_done = true; excluded = true;
      time_snapshot(state.match_frame);
    }
  }
  if (r.have_last)
    r.frames.push_back({float(frame_ms), vs_match, fighting,
                        counters.disc_reads != r.last_disc_reads, false});
  if (counters.retraces % 600 == 0) {
#ifdef __SWITCH__
    say("retrace %u: scene %u/%u, match frame %u, core %d measures %u MHz", counters.retraces, state.scene_major, state.scene, state.match_frame,
        (int)svcGetCurrentProcessorNumber(), switch_measure_cpu_mhz());
#else
    say("retrace %u: scene %u/%u, match frame %u", counters.retraces, state.scene_major, state.scene, state.match_frame);
#endif
  }
  r.last_match_frame = game_frame;
  r.last_disc_reads = counters.disc_reads;
  r.last = Clock::now();   // the digest text, the comparison, the snapshot timing and the progress line are not part of the next frame
  r.have_last = true;
  (void)excluded;
  if (r.options.profile) hostprof::discount(hostprof::now() - observer_in);   // this function is not part of whichever service called it
}

// Fixed pure-CPU and memory work, so a run says how fast the machine really is at that moment.
double timed_ms(void (*work)()) { const auto t = Clock::now(); work(); return ms_since(t); }
volatile uint64_t calibration_sink;
void work_integer() { uint64_t x = 1; for (int i = 0; i < 12000000; ++i) { x = x * 6364136223846793005ull + 1442695040888963407ull; x ^= x >> 29; } calibration_sink = x; }
void work_float() { double d = 1.0; for (int i = 0; i < 6000000; ++i) d = d * 1.0000001 + 0.5; calibration_sink = uint64_t(d); }
std::vector<uint32_t> calibration_table;
void work_memory() {      // a random walk through 64 MiB: almost every step misses every cache
  uint32_t at = 0; for (int i = 0; i < 400000; ++i) at = calibration_table[at]; calibration_sink = at;
}
void work_copy() { static std::vector<uint8_t> a(16u << 20, 1), b(16u << 20); std::memcpy(b.data(), a.data(), a.size()); calibration_sink = b[4097]; }
void calibrate(const char* when) {
  if (calibration_table.empty()) {
    const uint32_t n = (64u << 20) / 4;
    calibration_table.resize(n);
    // One cycle through all entries (a full-period generator), so the walk never gets stuck in a short loop.
    uint32_t at = 0;
    for (uint32_t i = 0; i < n; ++i) { const uint32_t next = uint32_t((uint64_t(at) * 5 + 12345) % n); calibration_table[at] = next; at = next; }
    work_copy();
  }
  double best[4] = {1e9, 1e9, 1e9, 1e9};
  void (*const works[4])() = {work_integer, work_float, work_memory, work_copy};
  for (int round = 0; round < 3; ++round) for (int i = 0; i < 4; ++i) best[i] = std::min(best[i], timed_ms(works[i]));
  say("calibration %s: integer %.2f ms, floating point %.2f ms, memory walk %.2f ms, 16 MiB copy %.2f ms (fixed work, best of 3)", when,
      best[0], best[1], best[2], best[3]);
}
#ifdef __SWITCH__
void measure_clock(const char* when) {
  uint32_t mhz[5];
  for (auto& m : mhz) m = switch_measure_cpu_mhz();
  std::sort(mhz, mhz + 5);
  say("clocks %s: the core measures %u MHz (5 runs: min %u, median %u, max %u) on core %d", when, mhz[2], mhz[0], mhz[2], mhz[4], (int)svcGetCurrentProcessorNumber());
}
#endif

void report_profile() {
  static const char* const kinds[3] = {"VS first-pass frames", "repeated frames in a rollback", "all other retraces (menus, loading)"};
  auto& r = run_state;
  const double tick_ms = 1000.0 / double(hostprof::frequency());
  for (int kind = 0; kind < 3; ++kind) {
    if (!r.prof_frames[kind]) continue;
    const double frames = double(r.prof_frames[kind]), frame_ms = r.prof_frame_ms[kind] / frames;
    std::vector<int> order;
    double services = 0; uint64_t calls = 0;
    for (int i = 0; i < hostprof::kSlots; ++i) if (r.prof_calls[kind][i]) { order.push_back(i); services += r.prof_ticks[kind][i] * tick_ms / frames; calls += r.prof_calls[kind][i]; }
    std::sort(order.begin(), order.end(), [&](int a, int b) { return r.prof_ticks[kind][a] > r.prof_ticks[kind][b]; });
    say("profile, %s: %llu frames, %.3f ms per frame, %.1f service calls per frame", kinds[kind], (unsigned long long)r.prof_frames[kind], frame_ms, calls / frames);
    say("  %-34s %10s %12s %7s", "where", "calls/frame", "ms/frame", "share");
    say("  %-34s %10s %12.4f %6.1f%%", "inside the game image", "", frame_ms - services, 100 * (frame_ms - services) / frame_ms);
    for (int i : order) {
      const double ms = r.prof_ticks[kind][i] * tick_ms / frames;
      if (ms < 0.0005 && r.prof_calls[kind][i] / frames < 0.5) continue;
      say("  %-34s %10.2f %12.4f %6.1f%%", hostprof::name(i) ? hostprof::name(i) : "?", r.prof_calls[kind][i] / frames, ms, 100 * ms / frame_ms);
    }
  }
  say("profile: 'host X' is time in that host service itself, 'game X' is time in a game function the host called back; each wrapped call adds about 20 instructions");
}

enum class Which { VsMatch, Fighting, All };
void report_timing(const char* label, Which which, bool with_disc_frames) {
  std::vector<float> ms;
  for (const auto& f : run_state.frames) {
    const bool wanted = which == Which::All || (which == Which::VsMatch ? f.vs_match : f.fighting);
    if (wanted && (with_disc_frames || !f.disc)) ms.push_back(f.ms);
  }
  if (ms.empty()) { say("%s: none", label); return; }
  double sum = 0; for (float v : ms) sum += v;
  std::vector<float> sorted = ms; std::sort(sorted.begin(), sorted.end());
  size_t late = 0; for (float v : ms) if (v > 1000.0f / 60) ++late;
  say("%s: %zu frames, avg %.3f ms, median %.3f, p99 %.3f, worst %.3f, over 16.67 ms: %zu", label, ms.size(), sum / ms.size(),
      sorted[sorted.size() / 2], sorted[size_t(sorted.size() * 0.99)], sorted.back(), late);
}

bool write_file(const std::string& path, const void* data, size_t size) {
  FILE* out = std::fopen(path.c_str(), "wb");
  if (!out) return false;
  const bool ok = std::fwrite(data, 1, size, out) == size;
  return std::fclose(out) == 0 && ok;
}

// A match must start from an empty memory card every time, as the reference runs did.
void empty_directory(const std::string& path) {
  mkdir(path.c_str(), 0777);
  DIR* dir = opendir(path.c_str());
  if (!dir) return;
  std::vector<std::string> names;
  while (dirent* entry = readdir(dir)) if (entry->d_name[0] != '.') names.push_back(entry->d_name);
  closedir(dir);
  for (const auto& name : names) std::remove((path + "/" + name).c_str());
}

// A script name is looked up among the embedded scripts (which are written to <out>/scripts,
// because the host's script reader takes a path), then as <out>/scripts/<name>.txt. A path is used as it is.
std::string script_path(const Options& options) {
  if (options.script.find('/') != std::string::npos || options.script.find(".txt") != std::string::npos) return options.script;
  const std::string dir = options.out_dir + "/scripts", path = dir + "/" + options.script + ".txt";
  for (size_t i = 0; i < mu_embedded_script_count; ++i) {
    const auto& s = mu_embedded_scripts[i];
    if (options.script != s.name) continue;
    mkdir(dir.c_str(), 0777);
    if (!write_file(path, s.begin, size_t(s.end - s.begin))) say("cannot write %s", path.c_str());
    return path;
  }
  return path;
}

void report_thread() {
  // The simulation relies on default floating-point behaviour: round to nearest, no flush-to-zero.
  unsigned long fpcr; __asm__ volatile("mrs %0, fpcr" : "=r"(fpcr));
  say("simulation thread: FPCR %lx%s", fpcr, fpcr ? " (EXPECTED 0)" : " (round to nearest, as expected)");
  int marker = 0;
#ifdef __SWITCH__
  MemoryInfo mi; u32 page_info;
  if (R_SUCCEEDED(svcQueryMemory(&mi, &page_info, (u64)(uintptr_t)&marker)))
    say("simulation thread: stack mapping %lx..%lx = %lu KiB (asked for 8192), %lu KiB below the current frame", (unsigned long)mi.addr,
        (unsigned long)(mi.addr + mi.size), (unsigned long)(mi.size >> 10), (unsigned long)(((uintptr_t)&marker - mi.addr) >> 10));
#else
  pthread_attr_t attr; void* base = nullptr; size_t size = 0;
  if (pthread_getattr_np(pthread_self(), &attr) == 0) {
    pthread_attr_getstack(&attr, &base, &size); pthread_attr_destroy(&attr);
    say("simulation thread: stack %zu KiB (asked for 8192), %zu KiB below the current frame", size >> 10, ((uintptr_t)&marker - (uintptr_t)base) >> 10);
  }
#endif
}

int simulate(const Options& options) {
  auto& r = run_state;
  r.options = options;
  r.digest.reserve(size_t(options.frames) * 330);
  r.frames.reserve(options.frames);
  report_thread();
#ifdef __SWITCH__
  {
    // Keep the simulation on one known core for the whole run.
    s32 preferred = -1; u64 allowed = 0;
    svcGetThreadCoreMask(&preferred, &allowed, CUR_THREAD_HANDLE);
    const int core = options.core >= 0 ? options.core : (int)svcGetCurrentProcessorNumber();
    const Result rc = svcSetThreadCoreMask(CUR_THREAD_HANDLE, core, 1u << core);
    svcSleepThread(0);
    say("simulation thread: allowed cores mask %llx, preferred %d; pinned to core %d (rc %x), now on core %d", (unsigned long long)allowed, (int)preferred,
        core, rc, (int)svcGetCurrentProcessorNumber());
    measure_clock("on the simulation thread");
  }
#endif
  calibrate("on the simulation thread, before the run");
  if (options.profile) hostprof::install();
  if (options.poll_ticks) { linux_host::set_poll_ticks(options.poll_ticks); say("EXPERIMENT: %u console clock ticks per host poll instead of 2048", options.poll_ticks); }
  if (!options.reference.empty()) {
    if (load_reference_file(options.reference, &r.reference)) say("reference digest from %s: %zu rows", options.reference.c_str(), r.reference.rows());
    else say("cannot read the reference digest %s", options.reference.c_str());
  } else if (load_reference(options.script, &r.reference)) say("reference digest for %s: %zu rows (x86-64 AVX2+FMA build)", options.script.c_str(), r.reference.rows());
  else say("no embedded reference digest for %s: exactness cannot be judged by this run", options.script.c_str());

  linux_host::Config config;
  config.iso_path = options.iso;
  config.game_path = options.game.empty() ? "(embedded)" : options.game;
  config.log_path = options.out_dir + "/host.log";
  config.card_dir = options.out_dir + "/card";
  config.input_script = script_path(options);
  config.max_frames = options.frames;
  config.pace = false; config.headless = true; config.no_gc_adapter = true; config.vanilla_game = true;
  config.has_rng_seed = true; config.rng_seed = 0x12345678;
  config.has_time_base = true; config.time_base = 0;
  empty_directory(config.card_dir);
  if (options.game.empty()) mac_elf::set_embedded_image(mu_embedded_game, size_t(mu_embedded_game_end - mu_embedded_game));

  say("disc %s | script %s | %u retraces | image %s | snapshot timing %s", options.iso.c_str(), options.script.c_str(), options.frames,
      config.game_path.c_str(), options.snapshot_at ? "on" : "off");
  std::string error;
  const auto t0 = Clock::now();
  if (!linux_host::initialize(config, &error)) { say("cannot start: %s", error.c_str()); linux_host::shutdown(); return 1; }
  say("started in %.0f ms; image at 0x82800000 (%u bytes)", ms_since(t0), linux_host::game_image_size());
  if (options.rollback_every) {
    // The reference state of each VS match frame, for comparing frames that are simulated again.
    uint32_t previous = 0;
    for (size_t i = 0; i < r.reference.rows(); ++i) {
      unsigned retrace = 0, major = 0, minor = 0, frame = 0;
      const char* text = r.reference.text.c_str() + r.reference.row[i];
      std::sscanf(text, "%u,%u,%u,%u", &retrace, &major, &minor, &frame);
      if (major == 2 && minor == 2 && frame && frame != previous) {
        const char* comma = std::strchr(text, ',');
        const uint32_t begin = uint32_t(comma + 1 - r.reference.text.c_str());
        r.reference_by_frame[frame] = {begin, r.reference.row[i + 1] - 1 - begin};
      }
      previous = frame;
    }
    say("rollback test: every %u VS match frames go back %u frames%s; %zu reference frames", options.rollback_every, options.rollback_depth,
        options.rollback_verify ? ", verifying the write tracking" : "", r.reference_by_frame.size());
  }
  if (!options.dirty_dump.empty()) dirty.out = std::fopen(options.dirty_dump.c_str(), "wb");
  linux_host::set_frame_observer(observe, nullptr);
  const auto t1 = Clock::now();
  const int result = linux_host::run();
  const double total = ms_since(t1);
  const auto stats = linux_host::counters();
  say("stopped with code %d after %u retraces in %.1f s: %llu disc reads, %llu FIFO bytes, %llu audio blocks", result, stats.retraces,
      total / 1000, (unsigned long long)stats.disc_reads, (unsigned long long)stats.fifo_bytes, (unsigned long long)stats.audio_blocks);
  linux_host::set_frame_observer(nullptr, nullptr);
  if (dirty.out) { std::fclose(dirty.out); dirty.out = nullptr; }
  const size_t hot_at_end = mu_rollback::hot_pages();
  const bool overflowed = mu_rollback::overflowed();
  mu_rollback::end();          // pages writable again before they are unmapped
  linux_host::shutdown();      // unloads the image and unmaps the three fixed ranges

  // Where the run went: retrace ranges per scene (major/minor). 2/2 is the VS match.
  say("scenes, this run:  %s", timeline(r.scenes, stats.retraces).c_str());
  if (r.reference.loaded()) {
    std::vector<Scene> expected;
    for (size_t i = 0; i < r.reference.rows() && i < stats.retraces; ++i) {
      unsigned retrace = 0, major = 0, minor = 0;
      std::sscanf(r.reference.text.c_str() + r.reference.row[i], "%u,%u,%u", &retrace, &major, &minor);
      note_scene(&expected, retrace, major, minor);
    }
    const std::string theirs = timeline(expected, uint32_t(std::min<size_t>(r.reference.rows(), stats.retraces)));
    if (theirs != timeline(r.scenes, stats.retraces)) say("scenes, reference: %s", theirs.c_str());
    else say("scenes: same sequence and timing as the reference");
  }

#ifdef __SWITCH__
  measure_clock("after the run");
#endif
  calibrate("on the simulation thread, after the run");
  if (options.profile) report_profile();
  if (r.match_first) say("VS match: retraces %u..%u", r.match_first, r.match_last);
  else say("VS match: NOT REACHED (the menu flow did not get to scene 2/2; see the scene lines and the host log for card errors)");
  report_timing("VS match frames, all", Which::VsMatch, true);
  report_timing("VS match frames without a disc read", Which::VsMatch, false);
  report_timing("any frames with fighters simulating (includes demo fights)", Which::Fighting, true);
  report_timing("all retraces (menus, loading, matches)", Which::All, true);
  say("each frame is the whole retrace on one core: simulation, the GX command stream (discarded), audio mixing (discarded)");
  if (options.snapshot_at && !r.snapshot_done) say("snapshot: NOT TIMED, the VS match never reached frame %u", options.snapshot_at);

  if (options.rollback_every) {
    say("rollback: %u rollbacks of %u frames; hot pages at the end %zu (%.2f MiB) of %zu tracked; write faults %llu%s", r.rb_count,
        options.rollback_depth, hot_at_end, hot_at_end / 256.0, mu_rollback::tracked_pages(), (unsigned long long)dirtytrack_faults(),
        overflowed ? "; HOT STORE OVERFLOWED (results invalid)" : "");
    if (!r.faults_per_frame.empty()) {
      std::vector<uint32_t> faults(r.faults_per_frame.begin() + 1, r.faults_per_frame.end());
      std::sort(faults.begin(), faults.end());
      uint64_t sum = 0; for (uint32_t f : faults) sum += f;
      if (!faults.empty())
        say("rollback: write faults per frame after the first: avg %.2f, p99 %u, worst %u (they are inside the frame times below)",
            double(sum) / faults.size(), faults[size_t(faults.size() * 0.99)], faults.back());
    }
    report_series("rollback: first-pass frame (simulated, drawn, audio mixed)", r.first_pass_ms);
    report_series(options.rollback_draw ? "rollback: repeated frame (drawn too: --rollback-draw)" : "rollback: repeated frame (simulated only: no drawing, no audio mixing)", r.repeated_ms);
    report_series("rollback: the new frame that ends a rollback", r.new_ms);
    report_series("rollback: save, per frame", r.save_ms);
    report_series("rollback: restore", r.restore_ms);
    char label[96];
    std::snprintf(label, sizeof label, "rollback: whole rollback frame (restore + %u repeated frames + 1 new, with saves)", options.rollback_depth);
    report_series(label, r.rollback_ms);
    if (options.rollback_diff) say("rollback diff: %u of %u rollbacks ended with state bytes different from the first pass", r.rb_diff_rollbacks, r.rb_count);
    if (r.rb_frame_jumps)
      say("rollback: %u retraces did not advance the match by exactly one frame (first at match frame %u): the scripted inputs slipped there, "
          "so a difference after that point says nothing about rollback", r.rb_frame_jumps, r.rb_first_jump);
    if (options.rollback_verify) say("rollback: tracking checked %zu times, writes that escaped it: %zu%s", r.rb_checks, r.rb_missed, r.rb_missed ? " (NOT EXACT)" : "");
    if (r.rb_different) say("rollback exactness: DIFFERENT in %u of %u VS match frame states, first at match frame %u", r.rb_different, r.rb_compared, r.rb_first_different);
    else say("rollback exactness: IDENTICAL, %u VS match frame states (first pass and repeated) equal the x86-64 reference", r.rb_compared);
  }
  const uint64_t hash = fnv1a64(r.digest);
  const std::string csv = options.out_dir + "/digest-" + (options.script.find('/') == std::string::npos ? options.script : std::string("custom")) + ".csv";
  say("digest: %u rows, fnv1a64 %016llx, %s %s", stats.retraces, (unsigned long long)hash,
      write_file(csv, r.digest.data(), r.digest.size()) ? "written to" : "COULD NOT WRITE", csv.c_str());
  if (options.rollback_every) say("digest: rows after the first rollback are shifted by the repeated frames; exactness is the rollback line above");
  else if (r.reference.loaded()) {
    if (!r.first_diff)
      say("digest vs x86-64 AVX2 reference: IDENTICAL for all %u rows compared%s", r.compared,
          r.compared < stats.retraces ? " (the reference is shorter than this run)" : "");
    else {
      say("digest vs x86-64 AVX2 reference: DIFFERENT. First differing retrace %u: %s", r.first_diff,
          first_difference(r.diff_ours, r.diff_reference).c_str());
      say("  this run : %s", r.diff_ours.c_str());
      say("  reference: %s", r.diff_reference.c_str());
      say("  differing rows: %u inside the VS match, %u outside, of %u compared", r.diff_in_match, r.diff_outside, r.compared);
    }
  }
  return result;
}

