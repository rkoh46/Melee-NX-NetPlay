// mu-native: runs the native engine's headless simulation and reports exactness and speed.
//
// One program for Horizon (an NRO started from the Homebrew Menu or over nxlink) and for aarch64
// Linux (the test build). It loads the game image at 0x82800000 (mu_elf.cpp, fixedmap_*.c), drives
// it with melee-unlocked's headless host services and a scripted match, and prints:
//   - a per-retrace state digest, written as CSV in the form melee-unlocked's --state-digest
//     writes, compared row by row with the embedded x86-64 reference: the first differing retrace
//     with both rows, and the scene timeline of both sides when they differ,
//   - ms per frame (average, median, 99th percentile, worst) for the frames of the match,
//   - the time of one full rollback snapshot (save and restore) of the game state.
// No picture, no sound output, no network, no controllers.
