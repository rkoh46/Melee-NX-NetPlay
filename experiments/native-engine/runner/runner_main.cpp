int main(int argc, char** argv) {
#ifdef __SWITCH__
  consoleInit(nullptr);
  socketInitializeDefault();
  nxlinkStdio();            // stdout and stderr go to the nxlink host when there is one
#endif
  Options options;
  bool help = false;
  for (int i = 1; i < argc; ++i) {
    const std::string arg = argv[i];
    auto next = [&]() -> std::string { return i + 1 < argc ? argv[++i] : ""; };
    if (arg == "--iso") options.iso = next();
    else if (arg == "--script") options.script = next();
    else if (arg == "--frames") options.frames = uint32_t(std::strtoul(next().c_str(), nullptr, 0));
    else if (arg == "--out") options.out_dir = next();
    else if (arg == "--game") options.game = next();
    else if (arg == "--snapshot-at") options.snapshot_at = uint32_t(std::strtoul(next().c_str(), nullptr, 0));
    else if (arg == "--print-digest") options.print_digest = true;
    else if (arg == "--dirty-dump") options.dirty_dump = next();
    else if (arg == "--rollback-test") {            // EVERY[:DEPTH], for example 30:7
      const std::string value = next();
      options.rollback_every = uint32_t(std::strtoul(value.c_str(), nullptr, 0));
      const size_t colon = value.find(':');
      if (colon != std::string::npos) options.rollback_depth = uint32_t(std::strtoul(value.c_str() + colon + 1, nullptr, 0));
      if (!options.rollback_depth || options.rollback_depth > 30 || options.rollback_every <= options.rollback_depth + 1) help = true;
    }
    else if (arg == "--rollback-verify") options.rollback_verify = true;
    else if (arg == "--rollback-keep-clock") options.rollback_keep_clock = true;
    else if (arg == "--rollback-draw") options.rollback_draw = true;
    else if (arg == "--rollback-diff") options.rollback_diff = true;
    else if (arg == "--reference") options.reference = next();
    else if (arg == "--profile") options.profile = true;
    else if (arg == "--poll-ticks") options.poll_ticks = uint32_t(std::strtoul(next().c_str(), nullptr, 0));
    else if (arg == "--core") options.core = int(std::strtol(next().c_str(), nullptr, 0));
    else if (arg == "--no-overclock") options.overclock = false;
    else if (arg == "--cpu-mhz") options.cpu_mhz = uint32_t(std::strtoul(next().c_str(), nullptr, 0));
    else if (arg == "--track-remap") dirtytrack_set_method(DIRTYTRACK_REMAP);   // Horizon: the other way to make pages read-only (dirtytrack.h)
    else help = true;
  }
  mkdir(options.out_dir.c_str(), 0777);
  run_log = std::fopen((options.out_dir + "/run.log").c_str(), "a");
  say("---- mu-native (native engine, headless) ----");
#ifdef __SWITCH__
  say("Horizon: applet type %d", appletGetAppletType());
  // Clocks, as the app does it (switch/src/switch_clocks.cpp): every timing below is at a known clock.
  SwitchClockResult clocks_before{};
  const bool clock_service = switch_clocks_init();
  if (clock_service) clocks_before = switch_clocks_read();
  say("clocks: at start cpu %u gpu %u mem %u MHz reported%s; the CPU core measures %u MHz", clocks_before.cpu_hz / 1000000u,
      clocks_before.gpu_hz / 1000000u, clocks_before.mem_hz / 1000000u, clock_service ? "" : " (clock service not reachable)", switch_measure_cpu_mhz());
  if (options.overclock && clock_service) {
    SwitchClockRequest request; request.cpu_mhz = options.cpu_mhz; request.mem_mhz = kSwitchClocksErista.mem_mhz;   // as the app, minus the GPU
    const SwitchClockResult now = switch_clocks_apply(request);
    say("clocks: requested cpu %u MHz (%s) and memory %u MHz (%s); now reported cpu %u, memory %u MHz", options.cpu_mhz, now.cpu_ok ? "accepted" : "REFUSED",
        request.mem_mhz, now.mem_ok ? "accepted" : "REFUSED", now.cpu_hz / 1000000u, now.mem_hz / 1000000u);
    say("clocks: sys-clk, when installed, applies its own profile a moment later and overrides this: trust the measured values below, not the request");
  } else say("clocks: left as they are (%s)", options.overclock ? "no clock service" : "--no-overclock");
#endif
  int result = 2;
  if (help || options.iso.empty() || !options.frames) usage();
  else {
    // The game runs its own main loop and expects a desktop-sized stack: give it its own thread.
    ThreadArgs args{options, 1};
    pthread_attr_t attr; pthread_attr_init(&attr); pthread_attr_setstacksize(&attr, 8u << 20);
    pthread_t thread;
    if (pthread_create(&thread, &attr, simulate_thread, &args) == 0) { pthread_join(thread, nullptr); result = args.result; }
    else say("cannot create the simulation thread");
    pthread_attr_destroy(&attr);
  }
  fixedmap_release_all();     // nothing should be left; harmless when it is not
  // The host keeps its own log (game messages, panics): add it to run.log so one file tells the story.
  if (run_log) {
    if (FILE* host = std::fopen((options.out_dir + "/host.log").c_str(), "r")) {
      char line[512];
      std::fputs("-- host.log --\n", run_log);
      while (std::fgets(line, sizeof line, host)) std::fputs(line, run_log);
      std::fclose(host);
    }
  }
#ifdef __SWITCH__
  say("clocks: the CPU core measures %u MHz at the end of the run", switch_measure_cpu_mhz());
  if (clock_service) {
    if (options.overclock && clocks_before.cpu_hz) {
      SwitchClockRequest back; back.cpu_mhz = clocks_before.cpu_hz / 1000000u; back.mem_mhz = clocks_before.mem_hz / 1000000u;
      const SwitchClockResult restored = switch_clocks_apply(back);
      say("clocks: cpu put back to %u MHz (%s)", restored.cpu_hz / 1000000u, restored.cpu_ok ? "ok" : "REFUSED");
    }
    switch_clocks_exit();
  }
#endif
  say("---- done (%d) ----", result);
  if (run_log) std::fclose(run_log);
#ifdef __SWITCH__
  svcSleepThread(2000000000ull);
  socketExit();
  consoleExit(nullptr);
#endif
  return result;
}
