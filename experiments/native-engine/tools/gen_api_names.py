#!/usr/bin/env python3
"""Writes the member names of MuHostApi and MuGameApi (melee-unlocked's mu_host.h), in order, as C++ tables
for the runner's per-service timing. usage: gen_api_names.py mu_host.h out.cpp"""
# SPDX-License-Identifier: GPL-3.0-or-later
import re, sys
text = open(sys.argv[1]).read()
out = ['// generated by tools/gen_api_names.py']
for struct, symbol in (('MuHostApi', 'mu_host_api'), ('MuGameApi', 'mu_game_api')):
    body = re.search(r'typedef struct ' + struct + r' \{(.*?)\n\} ' + struct + ';', text, re.S).group(1)
    body = re.sub(r'/\*.*?\*/', '', body, flags=re.S)
    members = [m.strip() for m in body.split(';') if m.strip()]
    names = re.findall(r'\(\*\s*(\w+)\)\s*\(', body)
    if len(names) != len(members) - 1:
        sys.exit('%s: expected one version field and function pointers only' % struct)
    out.append('extern const char* const %s_names[] = {%s};' % (symbol, ', '.join('"%s"' % n for n in names)))
    out.append('extern const int %s_name_count = %d;' % (symbol, len(names)))
open(sys.argv[2], 'w').write('\n'.join(out) + '\n')
