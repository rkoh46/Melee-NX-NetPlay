#!/usr/bin/env bash
# Builds the native-engine runner. Run ./fetch.sh first.
#   ./build.sh game     the game image (melee_game.so, AArch64 Linux ELF at 0x82800000) with GCC 15.2
#   ./build.sh linux    the runner for aarch64 Linux (test build)       -> build/native-engine/out/mu-native-linux
#   ./build.sh nro      the runner for Horizon                          -> build/native-engine/out/mu-native.nro
#   ./build.sh          all three
# Every container has a time limit and no network.
# SPDX-License-Identifier: GPL-3.0-or-later
set -euo pipefail
here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd -P)"
repo="$(cd "$here/../.." && pwd -P)"
work="$repo/build/native-engine"; tree="$work/mu"; out="$work/out"; gen="$work/gen"
LINUX_IMG="${MU_LINUX_IMAGE:-mu-arm-gcc15}"                    # docker build -t mu-arm-gcc15 -f linux-gcc15.Dockerfile .
NX_IMG="${MELEE_DOCKER_IMAGE:-melee-nx-netplay-build:latest}"
[ -d "$tree/port/linux" ] || { echo "run ./fetch.sh first" >&2; exit 1; }
mkdir -p "$out" "$gen"
# MU_TIMEOUT_SCALE multiplies the container time limits (app-build.sh sets it where the arm64 image runs under qemu).
dock() { local limit=$(( $1 * ${MU_TIMEOUT_SCALE:-1} )) image=$2; shift 2; timeout "$limit" docker run --rm --network none -v "$repo:/w" -w /w "$image" bash -ec "$*"; }

build_game() {
  dock 900 "$LINUX_IMG" '
    b=build/native-engine/game
    cmake -S build/native-engine/mu/sourceport/game -B $b -G Ninja -DCMAKE_C_COMPILER=/usr/local/bin/gcc -DCMAKE_CXX_COMPILER=/usr/local/bin/g++ \
      -DCMAKE_BUILD_TYPE=Release -DMELEE_CPU_BASELINE=AVX2 -DYOUGAME_AGENT_TEST_HOOK=OFF -DYOUGAME_RANKED_BRANCH=ON -DMELEE_DOUBLES=OFF >/dev/null
    cmake --build $b --target melee_game -j "$(nproc)" | tail -2
    cp $b/melee_game.so build/native-engine/out/melee_game.so
    cp $b/melee_game.snapexcl build/native-engine/out/melee_game.snapexcl'
  echo "built $out/melee_game.so"
}

# The image, the scripts and the reference digests are embedded so that one file (the NRO) is all nxlink has to send.
generate() {
  [ -f "$out/melee_game.so" ] || { echo "run ./build.sh game first" >&2; exit 1; }
  rm -rf "$gen/scripts"; mkdir -p "$gen/scripts"
  cp "$tree"/port/scripts/parity_*.txt "$tree"/port/scripts/native_vs_ko.txt "$gen/scripts/"
  python3 -I "$here/scripts/make_vs4_busy.py" "$tree/port/scripts/parity_vs_onett.txt" "$gen/scripts/vs4_busy.txt"
  {
    echo '.section .rodata'
    echo '.balign 16'; echo '.global mu_embedded_game'; echo 'mu_embedded_game: .incbin "build/native-engine/out/melee_game.so"'
    echo '.global mu_embedded_game_end'; echo 'mu_embedded_game_end:'
    echo '.global mu_embedded_snapexcl'; echo 'mu_embedded_snapexcl: .incbin "build/native-engine/out/melee_game.snapexcl"'
    echo '.global mu_embedded_snapexcl_end'; echo 'mu_embedded_snapexcl_end:'
    for f in "$gen"/scripts/*.txt; do n=$(basename "$f" .txt)
      echo ".balign 8"; echo "mu_script_$n: .incbin \"build/native-engine/gen/scripts/$n.txt\""; echo "mu_script_${n}_end:"
      echo ".global mu_script_$n"; echo ".global mu_script_${n}_end"
    done
    for f in "$here"/reference/*.csv.gz; do n=$(basename "$f" .csv.gz)
      echo ".balign 8"; echo "mu_ref_$n: .incbin \"experiments/native-engine/reference/$n.csv.gz\""; echo "mu_ref_${n}_end:"
      echo ".global mu_ref_$n"; echo ".global mu_ref_${n}_end"
    done
    echo '.section .note.GNU-stack,"",%progbits'
  } > "$gen/embedded.S"
  {
    echo '// generated by build.sh'
    echo '#include <cstddef>'; echo '#include <cstdint>'
    echo 'struct EmbeddedFile { const char* name; const uint8_t* begin; const uint8_t* end; };'
    for f in "$gen"/scripts/*.txt; do n=$(basename "$f" .txt); echo "extern \"C\" const uint8_t mu_script_$n[], mu_script_${n}_end[];"; done
    echo 'extern const EmbeddedFile mu_embedded_scripts[] = {'
    for f in "$gen"/scripts/*.txt; do n=$(basename "$f" .txt); echo "  {\"$n\", mu_script_$n, mu_script_${n}_end},"; done
    echo '};'
    echo 'extern const size_t mu_embedded_script_count = sizeof mu_embedded_scripts / sizeof mu_embedded_scripts[0];'
    for f in "$here"/reference/*.csv.gz; do n=$(basename "$f" .csv.gz); echo "extern \"C\" const uint8_t mu_ref_$n[], mu_ref_${n}_end[];"; done
    echo 'extern const EmbeddedFile mu_embedded_references[] = {'
    for f in "$here"/reference/*.csv.gz; do n=$(basename "$f" .csv.gz); echo "  {\"$n\", mu_ref_$n, mu_ref_${n}_end},"; done
    echo '};'
    echo 'extern const size_t mu_embedded_reference_count = sizeof mu_embedded_references / sizeof mu_embedded_references[0];'
  } > "$gen/embedded_tables.cpp"
  python3 -I "$here/tools/gen_api_names.py" "$tree/port/runtime/abi/mu_host.h" "$gen/api_names.cpp"
}

# Host services from melee-unlocked (headless: no SDL, no USB adapter, no renderer) plus our files.
SOURCES='build/native-engine/mu/port/linux/host_services.cpp build/native-engine/mu/port/linux/input_script.cpp
  build/native-engine/mu/port/runtime/hle/ax_ucode.cpp build/native-engine/mu/port/runtime/hle/native_savestate.cpp
  experiments/native-engine/runner/runner_main.cpp experiments/native-engine/runner/mu_elf.cpp experiments/native-engine/runner/rollback.cpp experiments/native-engine/runner/net_host.cpp experiments/native-engine/runner/hostprof.cpp build/native-engine/gen/api_names.cpp
  build/native-engine/gen/embedded_tables.cpp'
INCLUDES='-Iexperiments/native-engine/runner -Ibuild/native-engine/mu/port/linux -Ibuild/native-engine/mu/port/runtime/abi
  -Ibuild/native-engine/mu/port/runtime/hle -Ibuild/native-engine/mu/port/runtime/host -Ibuild/native-engine/mu/port/runtime/ppc
  -Ibuild/native-engine/mu/port/runtime/gx -Ibuild/native-engine/mu/native'
DEFINES='-DMU_FOREIGN_ELF -DMU_SQUAD=1 -DMELEE_NO_SLIPPI -DMELEE_PORT_VERSION=\"mu-native\" -DMELEE_LINUX_CPU_BASELINE=\"AArch64\"'
CXXFLAGS='-O2 -g -std=gnu++17 -Wall -fno-strict-aliasing -ffp-contract=on'
SOURCES=$(echo $SOURCES); INCLUDES=$(echo $INCLUDES)

# The app's Slippi netplay (this repository's port/runtime/hle, as a copy with patches/net-*.patch applied:
# net_sources.sh) and ENet, compiled against the app's own headers, for the runner's --net mode. No matchmaking,
# login or reporting code is linked.
NETSRC=build/native-engine/netsrc/port/runtime/hle
NET_INC='-Iexperiments/native-engine/runner -I'$NETSRC' -Iport/runtime/hle -Iport/runtime/host -Iport/runtime/gx -Iport/runtime/ppc -Iport/runtime -Iport/third_party/enet/include -Iport/third_party -Iport/third_party/nlohmann -Iport/app'
NET_DEF='-DSLIPPI_PIN_VERSION=\"3.7.0\" -DSLIPPI_PIN_TAG=\"v3.7.0\" -DSLIPPI_PIN_MATCHMAKING_URL=\"wss://invalid.invalid/\"'
NET_CXX="$NETSRC/slippi_online.cpp $NETSRC/slippi_net.cpp $NETSRC/slippi_offline.cpp $NETSRC/slippi_net_diag.cpp $NETSRC/slippi_match_quality.cpp $NETSRC/slippi_text.cpp $NETSRC/slippi_version.cpp experiments/native-engine/runner/netplay_bridge.cpp"
# MU_NET_SERVICES=1 builds the variant with the app's real services instead of stubs: the matchmaking
# service client (WebSocket, STUN), the user file, game reporting and HTTP (libcurl, mbedTLS on the Switch).
# Off by default; the outputs get the suffix "-services". Never point it at a real service from a
# development machine: SLIPPI_MM_URL (the app's own override) selects a local mock.
NET_SUFFIX=''; NET_LIBS_LINUX=''; NET_LIBS_NX=''; NET_URL_NX='wss://invalid.invalid/'; NET_URL_LINUX='wss://invalid.invalid/'
if [ "${MU_NET_SERVICES:-0}" = 1 ]; then
  NET_CXX="$NET_CXX $NETSRC/slippi_matchmaking_ws.cpp $NETSRC/slippi_report.cpp $NETSRC/slippi_http_curl.cpp $NETSRC/slippi_login.cpp"
  NET_DEF="$NET_DEF -DMU_NET_SERVICES"
  # The Switch build gets the service address the app is pinned to (tools/slippi_pin.json). The Linux
  # build never does: it is pinned to the loopback mock (tools/mock_matchmaking.py), so a development
  # machine cannot reach the real service even by accident.
  NET_URL_NX="$(python3 -I -c 'import json,sys; print(json.load(open(sys.argv[1]))["matchmaking_url"])' "$repo/tools/slippi_pin.json")"
  NET_URL_LINUX='ws://127.0.0.1:8765'
  NET_SUFFIX='-services'; NET_LIBS_LINUX='-lcurl'; NET_LIBS_NX='-lcurl -lmbedtls -lmbedx509 -lmbedcrypto'
fi
NET_C='callbacks compress host list packet peer protocol unix'
# \$1 C compiler, \$2 C++ compiler, \$3 extra flags, \$4 object directory, \$5 ld, \$6 objcopy; run inside a container.
# Everything but the bridge's own interface becomes local to the combined object.
NET_BUILD='net_build() { mkdir -p $4/net; for f in '"$NET_C"'; do $1 $3 -O2 -w -fvisibility=hidden -DHAS_FCNTL=1 -DHAS_POLL=1 -DHAS_INET_PTON=1 -DHAS_INET_NTOP=1 -DHAS_SOCKLEN_T=1 -DHAS_MSGHDR_FLAGS=1 -include arpa/inet.h -Iport/third_party/enet/include -c port/third_party/enet/$f.c -o $4/net/enet_$f.o; done; for f in '"$NET_CXX"'; do $2 $3 -std=gnu++20 -O2 -g -w -fvisibility=hidden -fvisibility-inlines-hidden '"$NET_INC $NET_DEF"' -c $f -o $4/net/$(basename $f .cpp).o; done; $5 -r --force-group-allocation $4/net/*.o -o $4/netplay.o; $6 --localize-hidden $4/netplay.o; }'

build_linux() {
  generate; bash "$here/net_sources.sh" "$repo/build/native-engine/netsrc" >/dev/null
  dock 600 "$LINUX_IMG" "
    o=build/native-engine/obj-linux$NET_SUFFIX; mkdir -p \$o
    gcc -O2 -g -fPIE -c experiments/native-engine/runner/fixedmap_linux.c -o \$o/fixedmap.o
    gcc -O2 -g -fPIE -c experiments/native-engine/runner/mu_imports.c -o \$o/mu_imports.o
    gcc -c build/native-engine/gen/embedded.S -o \$o/embedded.o
    gcc -O2 -g -fPIE -c experiments/native-engine/runner/dirtytrack_linux.c -o \$o/dirtytrack.o
    gcc -fPIE -c experiments/native-engine/runner/hostprof.S -o \$o/hostprof.o
    ${NET_BUILD//wss:\/\/invalid.invalid\//$NET_URL_LINUX}; net_build gcc g++ -fPIE \$o ld objcopy
    g++ $CXXFLAGS $DEFINES $INCLUDES $SOURCES \$o/fixedmap.o \$o/mu_imports.o \$o/embedded.o \$o/dirtytrack.o \$o/hostprof.o \$o/netplay.o -DMU_CARD_SIMPLE_COMMIT -pie -fPIE -lpthread $NET_LIBS_LINUX -lz -lm -o build/native-engine/out/mu-native-linux$NET_SUFFIX"
  echo "built $out/mu-native-linux$NET_SUFFIX"
}

build_nro() {
  generate; bash "$here/net_sources.sh" "$repo/build/native-engine/netsrc" >/dev/null
  dock 600 "$NX_IMG" "
    export PATH=/opt/devkitpro/devkitA64/bin:/opt/devkitpro/tools/bin:\$PATH
    o=build/native-engine/obj-nx$NET_SUFFIX; mkdir -p \$o
    ARCH='-march=armv8-a+crc+crypto -mtune=cortex-a57 -mtp=soft -fPIE -ffunction-sections -D__SWITCH__ -I/opt/devkitpro/libnx/include'
    aarch64-none-elf-gcc -O2 -g -Wall \$ARCH -c experiments/native-engine/runner/fixedmap_horizon.c -o \$o/fixedmap.o
    aarch64-none-elf-gcc -O2 -g -Wall \$ARCH -c experiments/native-engine/runner/mu_imports.c -o \$o/mu_imports.o
    aarch64-none-elf-gcc \$ARCH -c build/native-engine/gen/embedded.S -o \$o/embedded.o
    aarch64-none-elf-gcc -O2 -g -Wall \$ARCH -c experiments/native-engine/runner/dirtytrack_horizon.c -o \$o/dirtytrack.o
    aarch64-none-elf-gcc \$ARCH -c experiments/native-engine/runner/dirtytrack_horizon.S -o \$o/dirtytrack_entry.o
    aarch64-none-elf-gcc \$ARCH -c experiments/native-engine/runner/hostprof.S -o \$o/hostprof.o
    ${NET_BUILD//wss:\/\/invalid.invalid\//$NET_URL_NX}; net_build aarch64-none-elf-gcc aarch64-none-elf-g++ \"\$ARCH -idirafter /opt/devkitpro/portlibs/switch/include\" \$o aarch64-none-elf-ld aarch64-none-elf-objcopy
    aarch64-none-elf-g++ $CXXFLAGS \$ARCH $DEFINES $INCLUDES -Iswitch/src $SOURCES switch/src/switch_clocks.cpp \$o/fixedmap.o \$o/mu_imports.o \$o/embedded.o \$o/dirtytrack.o \$o/dirtytrack_entry.o \$o/hostprof.o \$o/netplay.o \
      -I/opt/devkitpro/portlibs/switch/include -specs=/opt/devkitpro/libnx/switch.specs -L/opt/devkitpro/portlibs/switch/lib -L/opt/devkitpro/libnx/lib -lnx $NET_LIBS_NX -lz -lnx -lm -o build/native-engine/out/mu-native$NET_SUFFIX.elf
    nacptool --create 'mu-native' 'Melee-NX-NetPlay' '0.1' build/native-engine/out/mu-native.nacp
    elf2nro build/native-engine/out/mu-native$NET_SUFFIX.elf build/native-engine/out/mu-native$NET_SUFFIX.nro --nacp=build/native-engine/out/mu-native.nacp
    ls -l build/native-engine/out/mu-native$NET_SUFFIX.nro"
  echo "built $out/mu-native$NET_SUFFIX.nro"
}

case "${1:-all}" in
  game) build_game ;;
  linux) build_linux ;;
  nro) build_nro ;;
  all) build_game; build_linux; build_nro ;;
  *) echo "usage: build.sh [game|linux|nro]" >&2; exit 2 ;;
esac
