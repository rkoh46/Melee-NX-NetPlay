#!/usr/bin/env bash
# Builds the native-engine runner. Run ./fetch.sh first.
#   ./build.sh game     the game image (melee_game.so, AArch64 Linux ELF at 0x82800000) with GCC 15.2
#   ./build.sh linux    the runner for aarch64 Linux (test build)       -> build/native-engine/out/mu-native-linux
#   ./build.sh nro      the runner for Horizon                          -> build/native-engine/out/mu-native.nro
#   ./build.sh          all three
# Every container has a time limit and no network.
# SPDX-License-Identifier: GPL-3.0-or-later
set -euo pipefail
here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd -P)"
repo="$(cd "$here/../.." && pwd -P)"
work="$repo/build/native-engine"; tree="$work/mu"; out="$work/out"; gen="$work/gen"
LINUX_IMG="${MU_LINUX_IMAGE:-mu-arm-gcc15}"                    # docker build -t mu-arm-gcc15 -f linux-gcc15.Dockerfile .
NX_IMG="${MELEE_DOCKER_IMAGE:-melee-nx-netplay-build:latest}"
[ -d "$tree/port/linux" ] || { echo "run ./fetch.sh first" >&2; exit 1; }
mkdir -p "$out" "$gen"
dock() { local limit=$1 image=$2; shift 2; timeout "$limit" docker run --rm --network none -v "$repo:/w" -w /w "$image" bash -ec "$*"; }

build_game() {
  dock 900 "$LINUX_IMG" '
    b=build/native-engine/game
    cmake -S build/native-engine/mu/sourceport/game -B $b -G Ninja -DCMAKE_C_COMPILER=/usr/local/bin/gcc -DCMAKE_CXX_COMPILER=/usr/local/bin/g++ \
      -DCMAKE_BUILD_TYPE=Release -DMELEE_CPU_BASELINE=AVX2 -DYOUGAME_AGENT_TEST_HOOK=OFF -DYOUGAME_RANKED_BRANCH=ON -DMELEE_DOUBLES=OFF >/dev/null
    cmake --build $b --target melee_game -j "$(nproc)" | tail -2
    cp $b/melee_game.so build/native-engine/out/melee_game.so'
  echo "built $out/melee_game.so"
}

# The image, the scripts and the reference digests are embedded so that one file (the NRO) is all nxlink has to send.
generate() {
  [ -f "$out/melee_game.so" ] || { echo "run ./build.sh game first" >&2; exit 1; }
  rm -rf "$gen/scripts"; mkdir -p "$gen/scripts"
  cp "$tree"/port/scripts/parity_*.txt "$tree"/port/scripts/native_vs_ko.txt "$gen/scripts/"
  python3 -I "$here/scripts/make_vs4_busy.py" "$tree/port/scripts/parity_vs_onett.txt" "$gen/scripts/vs4_busy.txt"
  {
    echo '.section .rodata'
    echo '.balign 16'; echo '.global mu_embedded_game'; echo 'mu_embedded_game: .incbin "build/native-engine/out/melee_game.so"'
    echo '.global mu_embedded_game_end'; echo 'mu_embedded_game_end:'
    for f in "$gen"/scripts/*.txt; do n=$(basename "$f" .txt)
      echo ".balign 8"; echo "mu_script_$n: .incbin \"build/native-engine/gen/scripts/$n.txt\""; echo "mu_script_${n}_end:"
      echo ".global mu_script_$n"; echo ".global mu_script_${n}_end"
    done
    for f in "$here"/reference/*.csv.gz; do n=$(basename "$f" .csv.gz)
      echo ".balign 8"; echo "mu_ref_$n: .incbin \"experiments/native-engine/reference/$n.csv.gz\""; echo "mu_ref_${n}_end:"
      echo ".global mu_ref_$n"; echo ".global mu_ref_${n}_end"
    done
    echo '.section .note.GNU-stack,"",%progbits'
  } > "$gen/embedded.S"
  {
    echo '// generated by build.sh'
    echo '#include <cstddef>'; echo '#include <cstdint>'
    echo 'struct EmbeddedFile { const char* name; const uint8_t* begin; const uint8_t* end; };'
    for f in "$gen"/scripts/*.txt; do n=$(basename "$f" .txt); echo "extern \"C\" const uint8_t mu_script_$n[], mu_script_${n}_end[];"; done
    echo 'extern const EmbeddedFile mu_embedded_scripts[] = {'
    for f in "$gen"/scripts/*.txt; do n=$(basename "$f" .txt); echo "  {\"$n\", mu_script_$n, mu_script_${n}_end},"; done
    echo '};'
    echo 'extern const size_t mu_embedded_script_count = sizeof mu_embedded_scripts / sizeof mu_embedded_scripts[0];'
    for f in "$here"/reference/*.csv.gz; do n=$(basename "$f" .csv.gz); echo "extern \"C\" const uint8_t mu_ref_$n[], mu_ref_${n}_end[];"; done
    echo 'extern const EmbeddedFile mu_embedded_references[] = {'
    for f in "$here"/reference/*.csv.gz; do n=$(basename "$f" .csv.gz); echo "  {\"$n\", mu_ref_$n, mu_ref_${n}_end},"; done
    echo '};'
    echo 'extern const size_t mu_embedded_reference_count = sizeof mu_embedded_references / sizeof mu_embedded_references[0];'
  } > "$gen/embedded_tables.cpp"
}

# Host services from melee-unlocked (headless: no SDL, no USB adapter, no renderer) plus our files.
SOURCES='build/native-engine/mu/port/linux/host_services.cpp build/native-engine/mu/port/linux/input_script.cpp
  build/native-engine/mu/port/runtime/hle/ax_ucode.cpp build/native-engine/mu/port/runtime/hle/native_savestate.cpp
  experiments/native-engine/runner/runner_main.cpp experiments/native-engine/runner/mu_elf.cpp
  build/native-engine/gen/embedded_tables.cpp'
INCLUDES='-Iexperiments/native-engine/runner -Ibuild/native-engine/mu/port/linux -Ibuild/native-engine/mu/port/runtime/abi
  -Ibuild/native-engine/mu/port/runtime/hle -Ibuild/native-engine/mu/port/runtime/host -Ibuild/native-engine/mu/port/runtime/ppc
  -Ibuild/native-engine/mu/port/runtime/gx -Ibuild/native-engine/mu/native'
DEFINES='-DMU_FOREIGN_ELF -DMU_SQUAD=1 -DMELEE_NO_SLIPPI -DMELEE_PORT_VERSION=\"mu-native\" -DMELEE_LINUX_CPU_BASELINE=\"AArch64\"'
CXXFLAGS='-O2 -g -std=gnu++17 -Wall -fno-strict-aliasing -ffp-contract=on'
SOURCES=$(echo $SOURCES); INCLUDES=$(echo $INCLUDES)

build_linux() {
  generate
  dock 600 "$LINUX_IMG" "
    o=build/native-engine/obj-linux; mkdir -p \$o
    gcc -O2 -g -fPIE -c experiments/native-engine/runner/fixedmap_linux.c -o \$o/fixedmap.o
    gcc -O2 -g -fPIE -c experiments/native-engine/runner/mu_imports.c -o \$o/mu_imports.o
    gcc -c build/native-engine/gen/embedded.S -o \$o/embedded.o
    g++ $CXXFLAGS $DEFINES $INCLUDES $SOURCES \$o/fixedmap.o \$o/mu_imports.o \$o/embedded.o -DMU_CARD_SIMPLE_COMMIT -pie -fPIE -lpthread -lz -lm -o build/native-engine/out/mu-native-linux"
  echo "built $out/mu-native-linux"
}

build_nro() {
  generate
  dock 600 "$NX_IMG" "
    export PATH=/opt/devkitpro/devkitA64/bin:/opt/devkitpro/tools/bin:\$PATH
    o=build/native-engine/obj-nx; mkdir -p \$o
    ARCH='-march=armv8-a+crc+crypto -mtune=cortex-a57 -mtp=soft -fPIE -ffunction-sections -D__SWITCH__ -I/opt/devkitpro/libnx/include'
    aarch64-none-elf-gcc -O2 -g -Wall \$ARCH -c experiments/native-engine/runner/fixedmap_horizon.c -o \$o/fixedmap.o
    aarch64-none-elf-gcc -O2 -g -Wall \$ARCH -c experiments/native-engine/runner/mu_imports.c -o \$o/mu_imports.o
    aarch64-none-elf-gcc \$ARCH -c build/native-engine/gen/embedded.S -o \$o/embedded.o
    aarch64-none-elf-g++ $CXXFLAGS \$ARCH $DEFINES $INCLUDES $SOURCES \$o/fixedmap.o \$o/mu_imports.o \$o/embedded.o \
      -I/opt/devkitpro/portlibs/switch/include -specs=/opt/devkitpro/libnx/switch.specs -L/opt/devkitpro/portlibs/switch/lib -L/opt/devkitpro/libnx/lib -lz -lnx -lm -o build/native-engine/out/mu-native.elf
    nacptool --create 'mu-native' 'Melee-NX-NetPlay' '0.1' build/native-engine/out/mu-native.nacp
    elf2nro build/native-engine/out/mu-native.elf build/native-engine/out/mu-native.nro --nacp=build/native-engine/out/mu-native.nacp
    ls -l build/native-engine/out/mu-native.nro"
  echo "built $out/mu-native.nro"
}

case "${1:-all}" in
  game) build_game ;;
  linux) build_linux ;;
  nro) build_nro ;;
  all) build_game; build_linux; build_nro ;;
  *) echo "usage: build.sh [game|linux|nro]" >&2; exit 2 ;;
esac
