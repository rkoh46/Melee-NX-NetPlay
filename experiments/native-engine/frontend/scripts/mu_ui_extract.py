#!/usr/bin/env python3
# Takes melee-unlocked's own interface code out of the fetched tree for the Switch app's MU interface (src/mu_panel.cpp,
# src/mu_home.cpp). Nothing is rewritten: whole functions and blocks are copied verbatim by their first and last lines,
# so a new melee-unlocked release that moves them fails here, loudly, instead of drifting.
#   mu_ui_extract.py <fetched mu tree> <out dir>
# Writes into <out dir>:
#   pc_settings_visuals.inl, settings_page_navigation.h, settings_imgui_input.h, settings_search.h, gd_text.inl,
#   font_metrics.h, motion.h   verbatim copies (port/runtime/gx, port/runtime/gx/ui_sources/gd_melee)
#   mu_panel_parts.inc          functions and blocks of port/runtime/gx/pc_settings.cpp (see PARTS)
#   mu_launcher_parts.inc       the launcher's palette and layout constants (port/app/launcher.cpp) and its accent theme
#                               (port/app/launcher_theme.h, without its <windows.h>; COLORREF comes from the includer)
# The copies keep melee-unlocked's licence (GPL-2.0-or-later, the SPDX lines of the files they come from).
# SPDX-License-Identifier: GPL-3.0-or-later
import os
import sys

tree, out = sys.argv[1], sys.argv[2]
gx = os.path.join(tree, "port/runtime/gx")
app = os.path.join(tree, "port/app")
os.makedirs(out, exist_ok=True)


def read(path):
    with open(path, encoding="utf-8") as f:
        return f.read().split("\n")


def write(name, text):
    path = os.path.join(out, name)
    old = None
    if os.path.exists(path):
        with open(path, encoding="utf-8") as f:
            old = f.read()
    if old != text:   # only a change gets a new time stamp, so the next build sees exactly that
        with open(path, "w", encoding="utf-8") as f:
            f.write(text)


def function(lines, signature, src):
    """A whole top-level function: from the line starting with `signature` to the next line that is exactly '}'."""
    for i, line in enumerate(lines):
        if line.startswith(signature):
            for j in range(i, len(lines)):
                if lines[j] == "}":
                    return lines[i:j + 1]
            break
    sys.exit(f"mu_ui_extract: {signature!r} not found in {src}")


def block(lines, first, last, src, inner=False, exact=False):
    """The lines from the one equal to `first` (stripped) to the next one equal to `last` (stripped); without the
    first and last line when `inner`."""
    for i, line in enumerate(lines):
        if line.strip() == first:
            for j in range(i + 1, len(lines)):
                if lines[j].strip() == last or (not exact and lines[j].strip().endswith(last)):
                    return lines[i + 1:j] if inner else lines[i:j + 1]
            break
    sys.exit(f"mu_ui_extract: block {first!r} .. {last!r} not found in {src}")


# Verbatim copies.
for src, name in [("pc_settings_visuals.inl", None), ("settings_page_navigation.h", None), ("settings_imgui_input.h", None),
                  ("settings_search.h", None), ("ui_sources/gd_melee/text.inl", "gd_text.inl"),
                  ("ui_sources/gd_melee/font_metrics.h", "font_metrics.h"), ("ui_sources/gd_melee/motion.h", "motion.h")]:
    text = "\n".join(read(os.path.join(gx, src)))
    if name == "gd_text.inl":
        text = text.replace('#include "font_metrics.h"', '#include "font_metrics.h"   // (gen/mu_ui copy)')
    write(name or os.path.basename(src), text)

# pc_settings.cpp: the Clean side appearance (menu style 0, melee-unlocked's default) as settings_frame draws it.
pc = os.path.join(gx, "pc_settings.cpp")
P = read(pc)
parts = ["// Generated by frontend/scripts/mu_ui_extract.py from melee-unlocked's port/runtime/gx/pc_settings.cpp",
         "// (GPL-2.0-or-later). Verbatim; included by src/mu_panel.cpp inside namespace gx.", ""]
for sig in ["static void draw_settings_icon(", "static void settings_clean_chrome(", "static void settings_clean_home("]:
    parts += function(P, sig, pc) + [""]
# The panel's slide in and out (GD Melee's hub_motion keyframes) and the Clean pages' own slide.
parts.append("static void mu_settings_motion(SettingsState& state) {")
parts += block(P, "if (!state.panel_anim_initialized) {", "0.0f, 14.0f);", pc)
parts += ["}", ""]
# A Clean category page's header: the X, the "< CATEGORIES" card.
parts.append("static void mu_settings_clean_detail_header(SettingsState& state) {")
parts += block(P, "} else if (clean_detail_theme) {", "ImGui::SetCursorScreenPos(ImVec2(p.x + 18.0f, p.y + 153.0f));", pc, inner=True)
parts.append("      ImGui::SetCursorScreenPos(ImVec2(p.x + 18.0f, p.y + 153.0f));")
parts += ["}", ""]
# A page's entrance (offset and fade), with the panel's options as the includer gives them.
parts.append("template <class Options> static void mu_settings_page_entrance(SettingsState& state, const Options& options) {")
parts += block(P, "if (state.content_anim_tab < 0) {", "0.72f + 0.28f * page_ease);", pc)
parts += ["}", ""]
# The panel's look (settings_context_create): ImGui's dark style with melee-unlocked's colours, rounding and spacing.
parts.append("static void mu_settings_style() {")
parts += block(P, "ImGui::StyleColorsDark();", "style.ScaleAllSizes(1.15f);", pc)
parts += ["}", ""]
# The page's scrolling child: smooth scroll that follows controller navigation.
parts.append("static void mu_settings_smooth_scroll() {")
parts.append("      constexpr bool gd_page = false;   // (mu_ui_extract.py: the GD Melee look is not drawn here)")
parts += block(P, "// Smooth wheel scrolling at the presented frame rate. ImGui's own wheel scroll jumps a whole",
               "storage->SetFloat(applied_id, next);", pc)
parts += ["}", ""]
write("mu_panel_parts.inc", "\n".join(parts) + "\n")
# The panel's render-side state (port/runtime/gx/pc_settings_shared.h), included before the visuals.
sh = os.path.join(gx, "pc_settings_shared.h")
write("mu_settings_state.inc", "// Generated by frontend/scripts/mu_ui_extract.py from melee-unlocked's port/runtime/gx/pc_settings_shared.h\n"
      "// (GPL-2.0-or-later). Verbatim.\n" + "\n".join(block(read(sh), "struct SettingsState {", "};", sh, exact=True)) + "\n")

# The launcher: palette and layout constants, and the accent theme.
L = read(os.path.join(app, "launcher.cpp"))
lp = ["// Generated by frontend/scripts/mu_ui_extract.py from melee-unlocked's port/app/launcher.cpp and launcher_theme.h",
      "// (GPL-2.0-or-later). Verbatim; included by src/mu_home.cpp.", ""]
lp += block(L, "// Client area in layout units; S() turns these into pixels for the current DPI.",
            "const COLORREF NO_FILL = CLR_INVALID;", os.path.join(app, "launcher.cpp"))
T = [l for l in read(os.path.join(app, "launcher_theme.h")) if l.strip() not in ("#include <windows.h>", "#pragma once")]
lp += [""] + T
write("mu_launcher_parts.inc", "\n".join(lp) + "\n")
print(f"mu_ui_extract: {out}")
