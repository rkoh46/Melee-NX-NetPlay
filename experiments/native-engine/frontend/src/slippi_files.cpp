// Slippi's menu files for play mode. melee-unlocked's game shows Slippi's online menus when its host sets
// the Slippi-menus option bit and serves Slippi's copies of thirteen disc files in place of the disc's
// (port/app/source_host.cpp load_system_files in the fetched tree). Ten of them are the disc's own file
// with Slippi's VCDIFF patch applied, the others are Slippi's files, two of which link to assets on the
// player's disc. This repository vendors Slippi 3.7.0's patches and files (port/slippi_sys) and has the
// decoder and the link resolver (port/runtime/host/vcdiff.cpp, port/runtime/hle/slippi_hsd_link.cpp); the
// build embeds the files, because this program has no RomFS.
// Nothing here talks to a server: these are menu pictures and texts.
